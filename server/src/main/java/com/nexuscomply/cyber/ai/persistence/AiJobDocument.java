package com.nexuscomply.cyber.ai.persistence;

import org.springframework.data.annotation.Id;
import org.springframework.data.mongodb.core.index.Indexed;
import org.springframework.data.mongodb.core.mapping.Document;

import java.time.Instant;
import java.util.LinkedHashMap;
import java.util.Map;

/**
 * MongoDB document representation for ai_jobs collection (schema1.md section 18).
 *
 * <p>Tracks asynchronous AI analysis operations.
 *
 * <p>Indexes per schema1.md section 18:
 * status, type, configurationId, versionId, createdBy, createdAt.
 */
@Document(collection = "ai_jobs")
public class AiJobDocument {

    @Id
    private String id;

    @Indexed
    private String type = "UNKNOWN_SYNTAX_ANALYSIS";

    @Indexed
    private String status = "COMPLETED";

    @Indexed
    private String configurationId;

    @Indexed
    private String versionId;

    private Map<String, Object> input = new LinkedHashMap<>();
    private Map<String, Object> result = new LinkedHashMap<>();
    private String error;

    private Instant startedAt;
    private Instant completedAt;

    @Indexed
    private String createdBy = "SYSTEM";

    @Indexed
    private Instant createdAt;

    private Instant updatedAt;

    public AiJobDocument() {}

    public String getId() {
        return id;
    }

    public void setId(String id) {
        this.id = id;
    }

    public String getType() {
        return type;
    }

    public void setType(String type) {
        this.type = type;
    }

    public String getStatus() {
        return status;
    }

    public void setStatus(String status) {
        this.status = status;
    }

    public String getConfigurationId() {
        return configurationId;
    }

    public void setConfigurationId(String configurationId) {
        this.configurationId = configurationId;
    }

    public String getVersionId() {
        return versionId;
    }

    public void setVersionId(String versionId) {
        this.versionId = versionId;
    }

    public Map<String, Object> getInput() {
        return input;
    }

    public void setInput(Map<String, Object> input) {
        this.input = input;
    }

    public Map<String, Object> getResult() {
        return result;
    }

    public void setResult(Map<String, Object> result) {
        this.result = result;
    }

    public String getError() {
        return error;
    }

    public void setError(String error) {
        this.error = error;
    }

    public Instant getStartedAt() {
        return startedAt;
    }

    public void setStartedAt(Instant startedAt) {
        this.startedAt = startedAt;
    }

    public Instant getCompletedAt() {
        return completedAt;
    }

    public void setCompletedAt(Instant completedAt) {
        this.completedAt = completedAt;
    }

    public String getCreatedBy() {
        return createdBy;
    }

    public void setCreatedBy(String createdBy) {
        this.createdBy = createdBy;
    }

    public Instant getCreatedAt() {
        return createdAt;
    }

    public void setCreatedAt(Instant createdAt) {
        this.createdAt = createdAt;
    }

    public Instant getUpdatedAt() {
        return updatedAt;
    }

    public void setUpdatedAt(Instant updatedAt) {
        this.updatedAt = updatedAt;
    }
}
